"""Build transparent MSB-first glyph masks for the existing draw_sprite ABI."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import hashlib
OUT=Path('apps/2048'); OUT.mkdir(exist_ok=True)
chars='-0123456789, BestNewgameCancelReset?GAMEOVR'
chars=''.join(sorted(set(chars)))
rows=['-- Generated by test/2048_design/generate_fonts.py; Lato, SIL OFL 1.1.','return {']
for style,sizes in [('b',[6,8,12,16,20,24,32,40,52]),('r',[24,40,52])]:
 for size in sizes:
  path=Path('/usr/share/fonts/truetype/lato')/('Lato-Heavy.ttf' if style=='b' else 'Lato-Regular.ttf')
  f=ImageFont.truetype(str(path),size)
  rows.append('["%s%d"]={height=%d,glyphs={'%(style,size,size))
  for c in chars:
   x0,y0,x1,y1=f.getbbox(c,anchor='ls'); w=max(1,x1-x0); h=max(1,y1-y0)
   im=Image.new('1',(w,h),1); ImageDraw.Draw(im).text((-x0,-y0),c,font=f,fill=0,anchor='ls')
   data=im.tobytes(); raw=''.join('\\%03d'%v for v in data)
   rows.append('[%d]={%d,%d,%d,%d,%d,"%s"},'%(ord(c),w,h,x0,y0,round(f.getlength(c)),raw))
  rows.append('}},')
rows.append('}')
(OUT/'fonts.lua').write_text('\n'.join(rows)+'\n')
print('fonts.lua',hashlib.sha256((OUT/'fonts.lua').read_bytes()).hexdigest())
